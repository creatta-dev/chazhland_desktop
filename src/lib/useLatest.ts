import { useRef } from 'react'
import type { RefObject } from 'react'

/**
 * Ref, всегда хранящий свежее значение. Замена россыпи «зеркал» вида
 * `const xRef = useRef(x); useEffect(() => { xRef.current = x }, [x])`.
 *
 * Присваивание идёт в теле рендера (а не в эффекте): значение свежее уже на этом рендере,
 * поэтому колбэки, живущие дольше рендера (WS-обработчики, таймеры, слушатели окна), читают
 * актуальное состояние, а не то, что было на момент их создания.
 *
 * Читать `.current` только из таких колбэков/эффектов — во время рендера это порвёт
 * конкурентный режим (значение зависит от порядка рендеров).
 */
export function useLatest<T>(value: T): RefObject<T> {
  const ref = useRef(value)
  ref.current = value
  return ref
}
